PRESERVAR = [(1, 2), (2, 3), (3, 0)]  # folha, rocha, petala (ja eram pixel art)


def sprite(grade):
    assert len(grade) == 16 and all(len(l) == 16 for l in grade), [len(l) for l in grade]
    im = Image.new("RGBA", (16, 16))
    for y, l in enumerate(grade):
        for x, ch in enumerate(l):
            v, a = NIVEIS[ch]
            im.putpixel((x, y), (v, v, v, a) if a else (0, 0, 0, 0))
    return im.resize((32, 32), Image.NEAREST)


if __name__ == "__main__":
    caminho = sys.argv[1]
    velho = Image.open(caminho).convert("RGBA")
    novo = Image.new("RGBA", (128, 128))
    for (r, c) in PRESERVAR:
        novo.paste(velho.crop((c * 32, r * 32, c * 32 + 32, r * 32 + 32)), (c * 32, r * 32))
    for (r, c), g in CELULAS.items():
        novo.paste(sprite(g), (c * 32, r * 32))
    novo.save(caminho)
    print("ok")
