"""Write RP/texts/*.lang from lang_data.py, keeping unrelated legacy keys."""
import os, sys
sys.path.insert(0, os.path.dirname(__file__))
from lang_data import L

RP = sys.argv[1]
FILES = {"pt_BR": 0, "en_US": 1, "es_ES": 2, "es_MX": 2}
for name, idx in FILES.items():
    path = os.path.join(RP, "texts", f"{name}.lang")
    legacy = {}
    if os.path.exists(path):
        for line in open(path, encoding="utf-8-sig").read().splitlines():
            if "=" in line and not line.startswith("#"):
                k, v = line.split("=", 1)
                k = k.strip()
                if k and k not in L and not k.startswith("item.") and not k.startswith("tile.") and not k.startswith("entity."):
                    legacy.setdefault(k, v.rstrip())
    out = ["## Vampire Craft 5 — generated by tools/gen_lang.py"]
    for k in sorted(L):
        out.append(f"{k}={L[k][idx]}\t#")
    open(path, "w", encoding="utf-8").write("\n".join(out) + "\n")
    print(name, len(L), "keys +", len(legacy), "legacy")
