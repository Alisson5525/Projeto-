"""Minimal JSON-with-comments support (vanilla Bedrock files contain comments)."""


def strip_comments(text):
    """Remove // and /* */ comments (vanilla files use them) outside strings."""
    out, i, n, in_str = [], 0, len(text), False
    while i < n:
        c = text[i]
        if in_str:
            out.append(c)
            if c == "\\":
                out.append(text[i + 1]); i += 2; continue
            if c == '"':
                in_str = False
        elif c == '"':
            in_str = True; out.append(c)
        elif text.startswith("//", i):
            while i < n and text[i] != "\n":
                i += 1
            continue
        elif text.startswith("/*", i):
            i = text.index("*/", i) + 2; continue
        else:
            out.append(c)
        i += 1
    return "".join(out)
